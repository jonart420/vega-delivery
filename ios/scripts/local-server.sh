#!/bin/sh
# Sets the app's default server address to this Mac on the local network
# (http://<name>.local:<port>). Rebuild the app afterwards. Addresses already stored in the app
# stay; change them on the login screen under "Server".
set -e
cd "$(dirname "$0")/.."
host="$(scutil --get LocalHostName)"
port="${1:-3100}"
printf '// Generated by scripts/local-server.sh – not in the repo.\nVD_DEFAULT_SERVER_URL = http:/$()/%s.local:%s\n' "$host" "$port" > Config/Local.xcconfig
echo "Default server: http://$host.local:$port"
